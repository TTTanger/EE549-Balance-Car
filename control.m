% ==================== 1. 完全基于传感器实测的物理参数 ====================
g = 9.81;
M = 0.32;            % 轮组平移总质量 (kg)
m = 0.44;            % 车身摆动总质量 (kg, 来自 Inertia Sensor)
l = 0.03241;         % 质心偏置力臂
I = 0.001028;        % 车身俯仰转动惯量 (kg*m^2, 来自 Inertia Sensor 对角线)

% ==================== 2. 状态空间矩阵计算 ====================
det_J = I * (M + m) + M * m * (l^2);

A = [ 0,  1,               0,               0;
    0,  0,     -(m^2 * g * l^2) / det_J,   0;
    0,  0,               0,               1;
    0,  0,       m * g * l * (M + m) / det_J, 0 ];

B = [ 0;
    -(m * l) / det_J;
    0;
    (M + m) / det_J ];

% ==================== 3. 权重配置 ====================
% 极弱的位移惩罚，0 速度惩罚，较弱的角度惩罚，0 角速度惩罚
Q = diag([0.1, 0, 10, 0]); 

% 极高的控制代价，强迫电机发力变得极其"懒惰"和"柔软"
R = 500;

% ==================== 4. 调用原生算法求解 K ====================
n = size(A, 1);
H = [ A,  -B * (R \ B');
    -Q,  -A' ];
[V, D] = eig(H);
[~, sort_indices] = sort(real(diag(D)));
V_stable = V(:, sort_indices(1:n));
P = real(V_stable(n+1:end, :) / V_stable(1:n, :));

% 恢复 LQR 的 K 矩阵计算
K = real(R \ (B' * P));

disp('-----------------------------------------');
disp('基于 Inertia Sensor 精确数据的 LQR 反馈增益 K:');
disp(K);
disp('-----------------------------------------');